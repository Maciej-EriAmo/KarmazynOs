# Own-compiler gate (Tor B seed): stage0 rustc builds kcc; kcc builds critical thermal.k0.
# Foreign: rustc (stage0 only), gcc (link). Own: kcc frontend+codegen.
#
#   .\toolchain\verify_kcc.ps1

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
if (-not (Test-Path (Join-Path $Root "toolchain\kcc\Cargo.toml"))) {
    $Root = Split-Path -Parent $MyInvocation.MyCommand.Path
    $Root = Split-Path -Parent $Root
}
$Kcc = Join-Path $Root "toolchain\kcc"
$Out = Join-Path $Root "out\kcc"
New-Item -ItemType Directory -Force -Path $Out | Out-Null

Write-Host "=== kcc verify (own compiler) ===" -ForegroundColor Cyan
Write-Host "kcc crate: $Kcc"

Push-Location $Kcc
try {
    Write-Host "`n[1] cargo test --release (stage0 rustc builds kcc)"
    cargo test --release
    if ($LASTEXITCODE -ne 0) { throw "cargo test failed" }

    Write-Host "`n[2] cargo build --release"
    cargo build --release
    if ($LASTEXITCODE -ne 0) { throw "cargo build failed" }

    $exe = Join-Path $Kcc "target\release\kcc.exe"
    if (-not (Test-Path $exe)) { $exe = Join-Path $Kcc "target\release\kcc" }

    $thermal = Join-Path $Kcc "examples\thermal.k0"
    $cOut = Join-Path $Out "thermal.c"
    $bin = Join-Path $Out "thermal_smoke"

    Write-Host "`n[3] kcc thermal.k0 → C (own frontend)"
    & $exe $thermal -o $cOut
    if ($LASTEXITCODE -ne 0) { throw "kcc emit failed" }
    if (-not (Test-Path $cOut)) { throw "missing $cOut" }
    $cText = Get-Content $cOut -Raw
    if ($cText -notmatch "k0_state_code") { throw "C missing k0_state_code" }
    if ($cText -notmatch "generated by kcc") { throw "C missing kcc banner" }

    Write-Host "`n[4] kcc --cc link smoke (foreign gcc OK)"
    & $exe $thermal --cc -o $bin
    if ($LASTEXITCODE -ne 0) { throw "kcc --cc failed" }

    $run = if (Test-Path "$bin.exe") { "$bin.exe" } else { $bin }
    Write-Host "`n[5] run thermal_smoke"
    & $run
    if ($LASTEXITCODE -ne 0) { throw "thermal_smoke exit $LASTEXITCODE (expected 0)" }
} finally {
    Pop-Location
}

Write-Host "`n=== KCC_VERIFY_OK ===" -ForegroundColor Green
Write-Host "Own compiler path: kcc. Foreign stage0: rustc. Foreign link: gcc."
exit 0
